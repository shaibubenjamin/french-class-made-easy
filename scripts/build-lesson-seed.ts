// Generates supabase/migrations/0005_seed_curriculum.sql from data/curriculum.
// Run with: npm run seed:lessons — re-running updates content in place
// (upsert on level + seq), so learner progress is kept.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { CURRICULUM } from "../data/curriculum/index.ts";
import { LEVELS } from "../shared/levels.ts";

const sql = (s: string) => `'${s.replaceAll("'", "''")}'`;

const rows = LEVELS.flatMap((level) =>
  CURRICULUM[level].map(
    (l) => `  (${sql(level)}, ${l.seq}, ${sql(l.theme)}, ${sql(JSON.stringify(l))}::jsonb, 'approved', 'curriculum')`,
  ),
);

const out = `-- GENERATED by scripts/build-lesson-seed.ts — do not edit by hand.
-- ${rows.length} built-in lessons (12 per level).
insert into public.lessons (level, seq, theme, content, status, model) values
${rows.join(",\n")}
on conflict (level, seq) do update
  set theme = excluded.theme, content = excluded.content, status = 'approved', updated_at = now();
`;

const target = fileURLToPath(new URL("../supabase/migrations/0005_seed_curriculum.sql", import.meta.url));
writeFileSync(target, out, "utf8");
console.log(`Wrote ${rows.length} lessons to ${target}`);
