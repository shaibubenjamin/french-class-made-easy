// Generates supabase/migrations/0003_seed_questions.sql from data/question-bank.ts.
// Run with: npm run seed:questions
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { QUESTION_BANK } from "../data/question-bank.ts";
import { shuffledOptions } from "../netlify/lib/seed.ts";

const sql = (s: string | null | undefined) => (s == null ? "null" : `'${s.replaceAll("'", "''")}'`);

const rows = QUESTION_BANK.map((q, i) => {
  const { options, answer } = shuffledOptions(q, i);
  return `  (${sql(q.level)}, ${sql(q.skill)}, 'mcq', ${sql(q.prompt)}, ${sql(q.passage)}, ${sql(
    JSON.stringify(options),
  )}::jsonb, ${answer}, ${sql(q.explanation)})`;
});

const out = `-- GENERATED by scripts/build-question-seed.ts — do not edit by hand.
-- ${QUESTION_BANK.length} placement questions (US-2.1).
insert into public.questions (level, skill, type, prompt, passage, options, answer, explanation) values
${rows.join(",\n")};
`;

const target = fileURLToPath(new URL("../supabase/migrations/0003_seed_questions.sql", import.meta.url));
writeFileSync(target, out, "utf8");
console.log(`Wrote ${QUESTION_BANK.length} questions to ${target}`);
